#!/usr/bin/env node
// Regenerates skills/agent-forge/references/practices-index.md from the per-phase
// practices files, which stay the single source of truth for each rule.
// Usage: node scripts/build-practices-index.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const PHASES = ['grill', 'architect', 'build', 'evals', 'ui'];
const ROOT = join(import.meta.dirname, '..');
export const INDEX = join(ROOT, 'skills', 'agent-forge', 'references', 'practices-index.md');
export const RULE = /^- \*\*([A-Z]{2}-\d{2})\*\* (.+?) — Source: (.+?) — Check: (.+?) — Verified: (\d{4}-\d{2}-\d{2})$/;

/**
 * Parse every rule of every phase.
 * @returns {{ rules: Array<{ id: string, phase: string, rule: string, source: string }>, errors: string[] }}
 */
export function readRules(root = ROOT) {
  const rules = [];
  const errors = [];
  for (const phase of PHASES) {
    const file = join(root, 'skills', `agent-forge-${phase}`, 'references', 'practices.md');
    if (!existsSync(file)) {
      errors.push(`ERROR: ${file} missing.`);
      continue;
    }
    readFileSync(file, 'utf8').split('\n').forEach((line, i) => {
      if (!line.startsWith('- **')) return;
      const m = line.match(RULE);
      if (!m) {
        errors.push(`ERROR: ${file}:${i + 1} is not "- **ID** rule — Source: [title](url) (org) — Check: … — Verified: YYYY-MM-DD".`);
        return;
      }
      rules.push({ id: m[1], phase, rule: m[2], source: m[3] });
    });
  }
  return { rules, errors };
}

/** Render the index: one line per rule, pointing at where the rule lives. */
export function renderIndex(rules) {
  const lines = [
    '# Practices index',
    '',
    '<!-- Generated by scripts/build-practices-index.mjs. Edit the per-phase practices.md files, not this one. -->',
    '',
    `${rules.length} rules from primary sources. Full text, source and check live in each phase's \`references/practices.md\`, one line per rule: \`- **ID** rule — Source: [title](url) (org) — Check: how it is verified — Verified: YYYY-MM-DD\`. Edit rules there, then run \`node scripts/build-practices-index.mjs\`; \`lint-skills\` fails while this index is stale.`,
    '',
  ];
  for (const phase of PHASES) {
    const own = rules.filter((r) => r.phase === phase);
    lines.push(`## ${phase} (${own.length})`, '');
    for (const r of own) {
      const short = r.rule.length > 110 ? `${r.rule.slice(0, 107).trimEnd()}…` : r.rule;
      const org = r.source.match(/\(([^()]+)\)\s*$/)?.[1] ?? '';
      lines.push(`- **${r.id}** ${short} _(${org})_ → [agent-forge-${phase}](../../agent-forge-${phase}/references/practices.md)`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { rules, errors } = readRules();
  if (errors.length) {
    for (const e of errors) process.stderr.write(`${e}\n`);
    process.exit(1);
  }
  const text = renderIndex(rules);
  if (process.argv.includes('--check')) {
    const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
    if (current !== text) {
      process.stderr.write('ERROR: practices-index.md is out of date. Run: node scripts/build-practices-index.mjs\n');
      process.exit(1);
    }
    process.stdout.write('OK: practices index up to date.\n');
  } else {
    writeFileSync(INDEX, text);
    process.stdout.write(`Wrote ${rules.length} rules to ${INDEX}\n`);
  }
}
